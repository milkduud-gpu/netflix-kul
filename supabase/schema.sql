-- netflix-kul database schema (Supabase / Postgres)
--
-- Mirrors the applied migrations, in order:
--   1. create_users         users profile table + signup trigger
--   2. create_tables        movies, watch_history, watchlist
--   3. create_rls_policies  row level security policies
--
-- Auth model
--   * auth.users (managed by Supabase Auth) holds credentials.
--   * public.users is the profile table; every user_id column references it.
--   * user_id columns are NOT NULL, default auth.uid() and cascade on delete,
--     so the app never sends a user id.
--
-- Access model
--   * movies is a shared catalog: signed-in users can read, nobody writes via the API.
--   * watch_history and watchlist are per-user: a user only sees and changes their own rows.
--   * Every policy is for role authenticated; anon has no access.
--
-- Notes
--   * rls_auto_enable() is an existing helper in the project and is not managed here.
--   * Tables start empty. Seed movies from the SQL editor or the service role.


-- ============================================================
-- Step 1: users
-- ============================================================

create table public.users (
  id           uuid primary key references auth.users (id) on delete cascade,
  email        text,
  display_name text,
  created_at   timestamptz not null default now()
);

-- Create the profile row automatically when someone signs up.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.users (id, email, display_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1))
  );
  return new;
end;
$$;

-- Only the auth trigger should run this, never API callers.
revoke execute on function public.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- ============================================================
-- Step 2: tables
-- ============================================================

create table public.movies (
  id          integer generated by default as identity primary key,
  title       text not null,
  genre       text not null,
  year        integer,
  rating      text,
  poster_path text,
  description text
);

create index movies_genre_idx on public.movies (genre);

create table public.watch_history (
  id         bigint generated always as identity primary key,
  user_id    uuid not null default auth.uid()
             references public.users (id) on delete cascade,
  movie_id   integer not null
             references public.movies (id) on delete cascade,
  watched_at timestamptz not null default now()
);

-- History page: a user's movies, newest first.
create index watch_history_user_watched_idx
  on public.watch_history (user_id, watched_at desc);
create index watch_history_movie_idx on public.watch_history (movie_id);

create table public.watchlist (
  user_id  uuid not null default auth.uid()
           references public.users (id) on delete cascade,
  movie_id integer not null
           references public.movies (id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (user_id, movie_id)
);

create index watchlist_movie_idx on public.watchlist (movie_id);

-- Explicit, even though rls_auto_enable() already turns this on.
alter table public.movies        enable row level security;
alter table public.watch_history enable row level security;
alter table public.watchlist     enable row level security;


-- ============================================================
-- Step 3: RLS policies
-- ============================================================
-- (select auth.uid()) is evaluated once per query instead of once per row.

-- users: a user can read and update only their own profile row.
-- Rows are created by the handle_new_user() trigger; no client insert or delete.
create policy "users select own"
  on public.users for select
  to authenticated
  using (id = (select auth.uid()));

create policy "users update own"
  on public.users for update
  to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- movies: shared catalog. Any signed-in user can read; no client writes.
create policy "movies select authenticated"
  on public.movies for select
  to authenticated
  using (true);

-- watch_history: a user can see, add and remove only their own rows.
create policy "watch_history select own"
  on public.watch_history for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "watch_history insert own"
  on public.watch_history for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "watch_history delete own"
  on public.watch_history for delete
  to authenticated
  using (user_id = (select auth.uid()));

-- watchlist: same rules as watch_history.
create policy "watchlist select own"
  on public.watchlist for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "watchlist insert own"
  on public.watchlist for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "watchlist delete own"
  on public.watchlist for delete
  to authenticated
  using (user_id = (select auth.uid()));
